"""M2-9 C follow-up: envelope-peak shift caused by one unresolved interferer (physics).

Physical basis for the tracking reverse tolerance (no 4TU data, no labels):
a tracked reflection (amplitude 1) plus one interferer of relative amplitude
``a`` and either polarity at time gap ``g`` (both the same wavelet), passed
through the fitting-branch chain (DC, Gaussian dewow sigma 1/f_c, zero-phase
band-pass 0.25-2 f_c), envelope = |hilbert|. The peak nearest the tracked
event moves by ``s(a, g)``; ``s_early(a) = max_g(-s)``, ``s_late(a) = max_g(s)``.

Two wavelets, both put on 500 MHz and dt 0.098 ns (4TU grid; the chain
scales with f_c, so results in periods carry over):
  * ricker: tests/synthetic_bscan.ricker form,
  * gprmax: the apex trace of gprMax M02 (data - background, trace 55),
    time axis scaled 400 -> 500 MHz, +-1.5 periods around its envelope peak,
    Tukey-tapered (a real FDTD wavelet with its own tail).

Outputs: data/processing/m29c_track_interference.csv (s per a, g, polarity;
         git-excluded, regenerated by this script),
         docs/processing/m29c_track_interference_max.csv (s_early, s_late per a),
         docs/processing/m29c_track_interference.png

Run: conda run -n gpr-dev python -I analysis/processing/m29c_track_interference.py
"""

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.interpolate import interp1d  # noqa: E402
from scipy.signal import hilbert  # noqa: E402
from scipy.signal.windows import tukey  # noqa: E402

PROJECT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT / "tests"))

from synthetic_bscan import ricker  # noqa: E402

from gpr_detection.preprocess.filters import bandpass, dewow, remove_dc  # noqa: E402

DOCS = PROJECT / "docs" / "processing"
DATA = PROJECT / "data" / "processing"  # git-excluded: the full (a, g) table is large
SYN = PROJECT / "data" / "synthetic_gprmax"
F_C = 500e6
T = 1e9 / F_C
DT = 0.098
N = 1024
T_MAIN = 40.0
AMPS = (0.05, 0.1, 0.15, 0.2, 0.25, 0.3, 0.4, 0.5)
GAPS = np.round(np.arange(-2.0, 2.0001, 0.01) * T, 6)


def gprmax_wavelet():
    raw = np.load(SYN / "M02.npy").astype(float)
    bg = np.load(SYN / "M02_bg.npy").astype(float)
    import json

    meta = json.loads((SYN / "M02.json").read_text(encoding="utf-8"))
    dt0 = meta["dt_ns"]
    col = bg.shape[1] // 2 if bg.ndim == 2 else None
    d = raw[:, 55] - (bg[:, col] if col is not None else bg)
    t0 = np.arange(len(d)) * dt0
    env = np.abs(hilbert(d))
    t_peak = meta["apex"]["envelope_peak_ns"]
    scale = 400e6 / F_C  # time axis compression to 500 MHz
    half = 1.5 * (1e9 / 400e6)
    m = np.abs(t0 - t_peak) <= half
    tt = (t0[m] - t_peak) * scale
    w = d[m] * tukey(m.sum(), 0.3)
    w = w / np.max(np.abs(hilbert(w)))
    f = interp1d(tt, w, bounds_error=False, fill_value=0.0)
    return lambda t: f(t), float(env[m].max())


def process(trace):
    x = trace[:, None]
    x = bandpass(dewow(remove_dc(x), DT, F_C), DT, F_C)
    return np.abs(hilbert(x[:, 0]))


def peak_time(env, t_ref):
    t = np.arange(N) * DT
    lo = int(np.floor((t_ref - 0.5 * T) / DT))
    hi = int(np.ceil((t_ref + 0.5 * T) / DT))
    seg = env[lo : hi + 1]
    k = int(np.argmax(seg))
    edge = k in (0, len(seg) - 1)
    i = lo + k
    if 0 < i < N - 1:
        l, c, r = env[i - 1], env[i], env[i + 1]
        den = l - 2 * c + r
        off = 0.0 if den == 0 else float(np.clip(0.5 * (l - r) / den, -0.5, 0.5))
    else:
        off = 0.0
    return t[i] + off * DT, edge


def main() -> None:
    t = np.arange(N) * DT
    gw, _ = gprmax_wavelet()
    wavelets = {"ricker": lambda tt: ricker(tt, F_C), "gprmax": gw}
    rows = []
    for name, w in wavelets.items():
        base = process(w(t - T_MAIN))
        t_ref, _ = peak_time(base, T_MAIN)
        for a in AMPS:
            for pol in (+1, -1):
                for g in GAPS:
                    env = process(w(t - T_MAIN) + pol * a * w(t - T_MAIN - g))
                    tp, edge = peak_time(env, t_ref)
                    rows.append(
                        dict(wavelet=name, a=a, polarity=pol, gap_ns=g, gap_T=g / T,
                             shift_ns=tp - t_ref, at_edge=edge)
                    )
    df = pd.DataFrame(rows)
    DATA.mkdir(parents=True, exist_ok=True)
    df.to_csv(DATA / "m29c_track_interference.csv", index=False, float_format="%.5f")
    ok = df[~df["at_edge"]]
    mx = (
        ok.groupby(["wavelet", "a"])
        .agg(s_early_ns=("shift_ns", lambda s: float(-s.min())), s_late_ns=("shift_ns", "max"))
        .reset_index()
    )
    mx["s_early_T"] = mx["s_early_ns"] / T
    mx["s_late_T"] = mx["s_late_ns"] / T
    mx["s_pp_ns"] = mx["s_early_ns"] + mx["s_late_ns"]
    mx.to_csv(DOCS / "m29c_track_interference_max.csv", index=False, float_format="%.4f")
    print(mx.to_string(index=False))

    fig, axes = plt.subplots(1, 2, figsize=(10, 3.6), constrained_layout=True, sharey=True)
    for ax, name in zip(axes, wavelets, strict=True):
        for a, color in zip((0.1, 0.2, 0.3), ("#7fb8e8", "#2a78d6", "#0b3d7a"), strict=True):
            for pol, ls in ((+1, "-"), (-1, "--")):
                s = df[(df.wavelet == name) & (df.a == a) & (df.polarity == pol)]
                ax.plot(s.gap_T, s.shift_ns, ls=ls, color=color, lw=1.1,
                        label=f"a={a} {'same' if pol > 0 else 'opposite'}")
        ax.axhline(-0.1, color="#e34948", lw=0.8, ls=":")
        ax.axhline(-0.3, color="#555555", lw=0.8, ls=":")
        ax.set_title(f"{name} wavelet, 500 MHz, dt 0.098 ns", fontsize=9)
        ax.set_xlabel("interferer gap g (periods; <0 = earlier)", fontsize=8)
        ax.grid(color="#eeeeee")
    axes[0].set_ylabel("envelope peak shift (ns)", fontsize=8)
    axes[1].legend(fontsize=6, ncol=2)
    fig.suptitle("Envelope-peak shift by one interferer after DC / dewow / band-pass "
                 "(red dotted: current reverse rule -0.1 ns; grey: back window -0.3 ns)", fontsize=9)
    fig.savefig(DOCS / "m29c_track_interference.png", dpi=120)
    plt.close(fig)


if __name__ == "__main__":
    main()
